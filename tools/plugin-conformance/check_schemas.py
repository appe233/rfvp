#!/usr/bin/env python3
"""Validate published candidate schemas against generated artifacts and negative cases.

  uv run --no-project --with jsonschema python tools/plugin-conformance/check_schemas.py [SAVE...]

Validates packages/plans generated by run.py (run it first), the ABI document's
context example, and the RFPM metadata block of any profiled save files given.
"""
import json
from pathlib import Path
import struct
import sys

from jsonschema import Draft202012Validator
from referencing import Registry, Resource

ROOT = Path(__file__).resolve().parents[2]
SCHEMAS = ROOT / "setsumei/plugins/schemas"
OUT = ROOT / "target/plugin-conformance"


def validators():
    resources = {}
    for path in SCHEMAS.glob("*.schema.json"):
        schema = json.loads(path.read_text())
        Draft202012Validator.check_schema(schema)
        resources[path.name] = schema
    registry = Registry().with_resources(
        [(name, Resource.from_contents(s)) for name, s in resources.items()]
        + [(s["$id"], Resource.from_contents(s)) for s in resources.values()])
    return {name.split(".")[0]: Draft202012Validator(s, registry=registry) for name, s in resources.items()}


def rfpm(path):
    data = path.read_bytes()
    state_len = struct.unpack("<I", data[-8:-4])[0]
    assert data[-4:] == b"RFVS", f"{path}: no RFVS state"
    start = len(data) - 8 - state_len
    assert data[start - 4:start] == b"RFPM", f"{path}: no RFPM metadata"
    meta_len = struct.unpack("<I", data[start - 8:start - 4])[0]
    return json.loads(data[start - 8 - meta_len:start - 8])


def main():
    v = validators()
    checked = 0

    def ok(kind, value, label):
        nonlocal checked
        errors = sorted(v[kind].iter_errors(value), key=str)
        assert not errors, f"{label}: {errors[0].message}"
        checked += 1

    def bad(kind, value, label):
        nonlocal checked
        assert not v[kind].is_valid(value), f"{label} unexpectedly valid"
        checked += 1

    manifests = sorted(OUT.glob("*/plugin.json"))
    assert manifests, "run tools/plugin-conformance/run.py first"
    for path in manifests:
        ok("manifest", json.loads(path.read_text()), str(path))
    ok("plan", json.loads((OUT / "game/plan.json").read_text()), "plan.json")
    base = json.loads(manifests[0].read_text())
    for field, value in [("schema_version", 2), ("id", "Upper"), ("api_major", 2), ("capabilities", ["x"]),
                         ("supported_scripts", []), ("supported_scripts", ["ABC"]), ("inputs", ["../x"]),
                         ("inputs", ["a//b"]), ("inputs", ["a\\b"]), ("inputs", ["c:x"]), ("inputs", ["./x"]),
                         ("inputs", ["a", "a"]), ("module", "/abs")]:
        bad("manifest", {**base, field: value}, f"manifest {field}={value!r}")
    bad("manifest", {**base, "extra": 1}, "manifest extra field")
    h = "0" * 64
    ok("context", {"script_sha256": h, "code_start": 4, "code_end": 1024,
                   "sources": [{"id": 1, "path": "patch.dat", "len": 4096, "sha256": h, "entries": []},
                               {"id": 2, "path": "patch.bin", "len": 8192, "sha256": h,
                                "entries": ["menu_bg", "title_logo"]}],
                   "originals": [{"path": "graph/menu_bg", "entry": "menu_bg"}]}, "ABI context example")
    bad("context", {"script_sha256": h, "code_start": 4, "code_end": 1024, "sources": [], "originals": [],
                    "extra": 0}, "context extra field")
    for plan in [{"strings": []}, {"strings": [{"offset": -1, "text": ""}], "resources": []},
                 {"strings": [{"offset": 6, "text": "a\u0000"}], "resources": []},
                 {"strings": [], "resources": [{"path": "menu", "source_id": 1, "entry": "menu"}]},
                 {"strings": [], "resources": [{"path": "graph/m", "source_id": 0, "entry": "m"}]}]:
        bad("plan", plan, f"plan {plan}")
    saves = [Path(p) for p in sys.argv[1:]]
    for path in saves:
        meta = rfpm(path)
        ok("save-metadata", meta, str(path))
        bad("save-metadata", {**meta, "nls": "latin1"}, "metadata nls")
    print(json.dumps({"status": "passed", "checks": checked, "manifests": len(manifests), "saves": len(saves)}))


if __name__ == "__main__":
    main()
